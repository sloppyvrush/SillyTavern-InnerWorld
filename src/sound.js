// Звук — это список голосов. Голос: { n: нота или частота, t: сдвиг, d: длина, v: громкость,
//   w: sine|square|triangle|sawtooth|noise, a: атака, s: доля длины на «удержание»,
//   g: во сколько раз уплывает высота (gd — за сколько секунд), vib: [частота, глубина],
//   h: обертоны [[кратность, громкость]], f: фильтр { t: тип, f: частота, to: куда уплывает, q } }.
let audio = null;
let master = null;
let noiseBuf = null;
let lastAt = 0;

function ctx() {
    if (!audio) {
        const AC = window.AudioContext || window.webkitAudioContext;
        if (!AC) return null;
        audio = new AC();
        // общий ограничитель: несколько звуков подряд не хрипят и не оглушают
        const comp = audio.createDynamicsCompressor();
        comp.threshold.value = -12;
        comp.knee.value = 6;
        comp.ratio.value = 4;
        comp.attack.value = 0.003;
        comp.release.value = 0.15;
        master = audio.createGain();
        master.gain.value = 1;
        master.connect(comp).connect(audio.destination);
    }
    if (audio.state === 'suspended') audio.resume().catch(() => {});
    return audio;
}

function noise(ac) {
    if (!noiseBuf) {
        const len = ac.sampleRate * 2;
        noiseBuf = ac.createBuffer(1, len, ac.sampleRate);
        const data = noiseBuf.getChannelData(0);
        for (let i = 0; i < len; i++) data[i] = Math.random() * 2 - 1;
    }
    return noiseBuf;
}

const STEPS = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

export function hz(n) {
    if (typeof n === 'number') return n;
    const m = /^([A-G])([#b]?)(-?\d)$/.exec(String(n || ''));
    if (!m) return 440;
    const k = STEPS[m[1]] + (m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0);
    const midi = (Number(m[3]) + 1) * 12 + k;
    return 440 * Math.pow(2, (midi - 69) / 12);
}

