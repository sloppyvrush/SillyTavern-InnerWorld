// Какая тема каким набором звучит. Остальные темы — обычный набор.
const THEME_SET = { bimbo: 'bimbo', cyber: 'cyber', medieval: 'medieval' };

function envelope(param, at, v, a, s, d) {
    param.setValueAtTime(0.0001, at);
    param.exponentialRampToValueAtTime(Math.max(v, 0.0002), at + a);
    if (s > 0) param.setValueAtTime(Math.max(v, 0.0002), at + a + s * (d - a));
    param.exponentialRampToValueAtTime(0.0001, at + d);
}

function voice(ac, dest, p, base) {
    const at = base + (p.t || 0);
    const d = p.d || 0.3;
    const v = p.v ?? 0.1;
    const s = p.s || 0;
    const w = p.w || 'sine';
    let out = dest;
    if (p.f) {
        const bq = ac.createBiquadFilter();
        bq.type = p.f.t || 'lowpass';
        bq.frequency.setValueAtTime(p.f.f, at);
        if (p.f.to) bq.frequency.exponentialRampToValueAtTime(p.f.to, at + d);
        bq.Q.value = p.f.q ?? 1;
        bq.connect(dest);
        out = bq;
    }
    const extra = p.h || (w === 'sine' || w === 'triangle' ? [[2, 0.15]] : []);
    const layers = w === 'noise' ? [[1, 1]] : [[1, 1], ...extra];
    for (const [ratio, k] of layers) {
        const len = ratio === 1 ? d : d * 0.7;
        const a = Math.min(p.a ?? 0.01, len * 0.9);
        const g = ac.createGain();
        envelope(g.gain, at, v * k, a, s, len);
        g.connect(out);
        let src;
        if (w === 'noise') {
            src = ac.createBufferSource();
            src.buffer = noise(ac);
            src.loop = true;
            src.start(at, Math.random() * 1.5);
        } else {
            src = ac.createOscillator();
            src.type = ratio === 1 ? w : 'sine';
            const f = hz(p.n) * ratio;
            src.frequency.setValueAtTime(f, at);
            if (p.g && p.g !== 1) src.frequency.exponentialRampToValueAtTime(f * p.g, at + (p.gd || d * 0.8));
            if (p.vib) {
                const lfo = ac.createOscillator();
                const lg = ac.createGain();
                lfo.frequency.value = p.vib[0];
                lg.gain.value = f * p.vib[1];
                lfo.connect(lg).connect(src.frequency);
                lfo.start(at);
                lfo.stop(at + len + 0.05);
            }
            src.start(at);
        }
        src.connect(g);
        src.stop(at + len + 0.05);
    }
}

function lengthOf(pattern) {
    return pattern.reduce((m, p) => Math.max(m, (p.t || 0) + (p.d || 0.3)), 0);
}

export function playSound(kind, theme = '') {
    try {
        const ac = ctx();
        if (!ac) return;
        const now = ac.currentTime;
        // несколько событий подряд встают в очередь, а не сливаются в кашу
        const start = Math.max(now + 0.02, lastAt);
        if (start - now > 2.5) return;
        const set = PATTERNS[THEME_SET[theme]] || PATTERNS.base || {};
        const pattern = set[kind] || (PATTERNS.base || {})[kind];
        if (!pattern) return;
        for (const p of pattern) voice(ac, master, p, start);
        lastAt = start + Math.min(lengthOf(pattern) * 0.7, 1.1);
    } catch (e) {
        console.warn('[Внутренний мир] звук не сыгран', e);
    }
}
